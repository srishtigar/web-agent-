def clean_text(text: str) -> str:
    """Clean and normalize text for better processing."""
    try:
        text = re.sub(r'\s+', ' ', text)
        text = re.sub(r'(skip to content|subscribe|follow us|contact us)\s*', '', text, flags=re.IGNORECASE)
        return text.strip()
    except Exception as e:
        logger.error("Error cleaning text: {}".format(e))
        return text

def extract_structured_data(soup: BeautifulSoup, url: str) -> List[str]:
    """
    Universal structured data extraction from any webpage.
    Captures key information like prices, numbers, dates, headings, etc.
    """
    structured_data = []

    try:
        # 1. Extract all headings (h1-h6) with their text
        for i in range(1, 7):
            headings = soup.find_all('h{}'.format(i))
            for h in headings[:5]:  # Top 5 headings per level
                text = h.get_text(strip=True)
                if text and len(text) > 3:
                    structured_data.append("HEADING: {}".format(text))

        # 2. Extract all numbers with context (prices, quantities, dates, etc.)
        number_patterns = [
            (r'(?:Rs\.?\s*|₹\s*)?([\d,]+\.?\d*)', 'PRICE/NUMBER'),
            (r'\$\s?([\d,]+\.?\d*)', 'PRICE/NUMBER'),
            (r'([\d,]+\.?\d+)%', 'PERCENTAGE'),
            (r'\b(\d{1,2}[-/]\d{1,2}[-/]\d{2,4})\b', 'DATE'),
        ]

        text_content = soup.get_text()
        for pattern, label in number_patterns:
            matches = re.findall(pattern, text_content)
            for match in matches[:20]:
                structured_data.append("{}: {}".format(label, match))

        # 3. Extract tables
        tables = soup.find_all('table')
        for idx, table in enumerate(tables[:3], 1):
            rows = table.find_all('tr')
            for row in rows[:10]:
                cells = row.find_all(['td', 'th'])
                if len(cells) >= 2:
                    row_text = ' | '.join([cell.get_text(strip=True) for cell in cells])
                    if row_text:
                        structured_data.append("TABLE_ROW: {}".format(row_text))

        # 4. Extract meta tags
        meta_desc = soup.find('meta', attrs={'name': 'description'})
        if meta_desc and meta_desc.get('content'):
            structured_data.append("META_DESCRIPTION: {}".format(meta_desc.get('content')))

        # 5. Extract financial/stock data classes
        financial_classes = [
            'price', 'stock-price', 'current-price', 'nse-price', 'bse-price',
            'market-cap', 'volume', 'high', 'low', 'change', 'percent-change',
            'value', 'amount', 'total', 'summary', 'stats', 'data'
        ]

        for cls in financial_classes:
            elements = soup.find_all(class_=re.compile(cls, re.IGNORECASE))
            for elem in elements[:5]:
                text = elem.get_text(strip=True)
                if text and len(text) < 200:
                    structured_data.append("{}: {}".format(cls.upper(), text))

        # 6. Extract strong/bold text
        bold_elements = soup.find_all(['strong', 'b'])
        for elem in bold_elements[:20]:
            text = elem.get_text(strip=True)
            if text and 3 < len(text) < 100:
                structured_data.append("IMPORTANT: {}".format(text))

        # 7. Extract list items
        lists = soup.find_all(['ul', 'ol'])
        for lst in lists[:5]:
            items = lst.find_all('li')
            for item in items[:10]:
                text = item.get_text(strip=True)
                if text and 3 < len(text) < 200:
                    structured_data.append("LIST_ITEM: {}".format(text))

        logger.info("✓ Extracted {} structured data points".format(len(structured_data)))

    except Exception as e:
        logger.error("Error extracting structured data: {}".format(e))

    return structured_data

def scrape_with_selenium(url: str, wait_time: int = 15) -> str:
    """Enhanced Selenium scraper with universal data extraction."""
    driver = None
    try:
        logger.info("🌐 Selenium scraping: {}".format(url))

        chrome_options = ChromeOptions()
        chrome_options.add_argument('--headless')
        chrome_options.add_argument('--no-sandbox')
        chrome_options.add_argument('--disable-dev-shm-usage')
        chrome_options.add_argument('--disable-blink-features=AutomationControlled')
        chrome_options.add_argument('--disable-extensions')
        chrome_options.add_argument('--disable-plugins')
        chrome_options.add_argument('user-agent=Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36')
        chrome_options.add_argument('--disable-gpu')

        driver = webdriver.Chrome(options=chrome_options)
        driver.set_page_load_timeout(20)

        driver.get(url)

        try:
            WebDriverWait(driver, wait_time).until(
                EC.presence_of_element_located((By.TAG_NAME, "body"))
            )
            logger.info("✓ Page body loaded")
        except:
            logger.warning("Timeout waiting for body on {}".format(url))

        time.sleep(7)

        try:
            expand_buttons = driver.find_elements(By.XPATH,
                "//button[contains(translate(., 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz'), 'more')] | "
                "//a[contains(translate(., 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz'), 'read more')] | "
                "//button[contains(translate(., 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz'), 'show')] | "
                "//a[contains(translate(., 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz'), 'view more')]"
            )

            for button in expand_buttons[:3]:
                try:
                    driver.execute_script("arguments[0].scrollIntoView(true);", button)
                    time.sleep(1)
                    driver.execute_script("arguments[0].click();", button)
                    logger.info("✓ Clicked expand button")
                    time.sleep(2)
                except:
                    pass
        except:
            pass

        driver.execute_script("window.scrollTo(0, document.body.scrollHeight);")
        time.sleep(4)
        driver.execute_script("window.scrollTo(0, document.body.scrollHeight/2);")
        time.sleep(3)
        driver.execute_script("window.scrollTo(0, 0);")
        time.sleep(3)

        html_content = driver.page_source
        soup = BeautifulSoup(html_content, 'html.parser')

        structured_data = extract_structured_data(soup, url)

        for script_or_style in soup(['script', 'style', 'nav', 'header', 'footer', 'aside']):
            script_or_style.extract()

        text = soup.get_text()
        text = clean_text(text)

        if structured_data:
            structured_section = "\n".join(structured_data)
            final_text = """
=== STRUCTURED DATA EXTRACTED ===
{}

=== FULL PAGE CONTENT ===
{}
""".format(structured_section, text)
        else:
            final_text = text

        logger.info("✓ Selenium complete: {} chars, {} structured data points".format(len(final_text), len(structured_data)))
        return final_text

    except Exception as e:
        logger.error("Selenium error: {}".format(e))
        return ""
    finally:
        if driver:
            try:
                driver.quit()
            except:
                pass

