        # ====================================================

        # Build context - prioritize structured data
        context_parts = []
        for idx, doc in enumerate(docs, 1):
            content = doc.page_content
            if "=== STRUCTURED DATA EXTRACTED ===" in content:
                context_parts.insert(0, "[HIGH PRIORITY CHUNK {}]:\n{}".format(idx, content))
