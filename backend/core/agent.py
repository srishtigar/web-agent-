@tool
def scrape_and_extract_links_tool(url: str, visited_urls: List[str]) -> Tuple[List[Document], List[str]]:
    """Scrapes URL and extracts links."""
    scraped_documents = []
    new_urls = []

    if url in visited_urls:
        return [], []

    try:
        use_selenium = len(visited_urls) == 0

        if use_selenium:
            full_text = scrape_with_selenium(url, wait_time=15)
        else:
            full_text = scrape_fallback(url)

        if not full_text or len(full_text) < 100:
            logger.warning("Primary scraper returned insufficient content, trying fallback")
            full_text = scrape_fallback(url) if use_selenium else scrape_with_selenium(url, wait_time=10)

        if full_text and len(full_text) > 50:
            doc = Document(
                page_content=full_text,
                metadata={"source": url, "url": url}
            )
            scraped_documents.append(doc)
            logger.info("✓ Document created: {} chars".format(len(full_text)))

        try:
            response = requests.get(url, timeout=8)
            soup = BeautifulSoup(response.text, 'html.parser')

            for a_tag in soup.find_all('a', href=True):
                try:
                    href = a_tag['href']
                    full_url = urljoin(url, href)
                    parsed_full_url = urlparse(full_url)
                    parsed_base_url = urlparse(url)

                    if (parsed_full_url.scheme in ['http', 'https'] and
                        parsed_full_url.netloc == parsed_base_url.netloc and
                        full_url not in visited_urls and
                        '#' not in parsed_full_url.fragment):
                        new_urls.append(full_url)
                except:
                    continue
        except Exception as e:
            logger.warning("Link extraction failed: {}".format(e))

    except Exception as e:
        logger.error("Scrape error: {}".format(e))

    return scraped_documents, list(set(new_urls[:10]))

